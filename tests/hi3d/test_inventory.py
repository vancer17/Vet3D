"""验证 Hi3D 只读盘点命令的发布契约。

测试在临时目录构造部署与 ASAR 夹具，检查文件指纹、锁定稳定性和失败后的输出边界。
"""

import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
from tempfile import TemporaryDirectory
import unittest


REPO = Path(__file__).resolve().parents[2]
CLI = REPO / "scripts" / "hi3d" / "inventory.py"
SKILLS = "runtime/prebuilt-skills/"
HELPER = b"def material():\n    return None\n"
HELPER_SOURCE = "tools/blender-tools/scripts/material_nodes.py"
PUBLIC_HELPER = "texture/scripts/material_nodes.py"
SHARED_HELPER = ".dependency-material/scripts/material_nodes.py"
APP_MEMBER = b'{"name":"fixture"}\n'
INVENTORY = "inventory.jsonl"
LOCK = "inventory.lock.json"


def digest(content):
    return hashlib.sha256(content).hexdigest()


def write_json(path, value):
    path.write_bytes((json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))


def write_archive(
    path: Path, *, unsafe_name: bool = False, bad_digest: bool = False, bad_block: bool = False
) -> None:
    """写入用于验证成员完整性和路径约束的合成 ASAR。

    :param path: 测试归档路径。
    :param unsafe_name: 是否在归档中插入越界成员路径。
    :param bad_digest: 是否让成员声明摘要与内容不符。
    :param bad_block: 是否只破坏分块声明摘要。
    """
    expected = digest(APP_MEMBER + b"modified") if bad_digest else digest(APP_MEMBER)
    member = {
        "size": len(APP_MEMBER),
        "offset": "0",
        "integrity": {
            "algorithm": "SHA256",
            "hash": expected,
            "blockSize": 4194304,
            "blocks": [digest(APP_MEMBER + b"modified") if bad_block else expected],
        },
    }
    files = {"package.json": member}
    if unsafe_name:
        files = {"..": {"files": files}}
    tree = json.dumps({"files": files}).encode("utf-8")
    padded_tree = tree + b"\0" * (-len(tree) % 4)
    header = struct.pack("<IIII", 4, len(padded_tree) + 8, len(padded_tree) + 4, len(tree))
    path.write_bytes(header + padded_tree + APP_MEMBER)


def fixture(resources):
    root = resources / SKILLS
    root.mkdir(parents=True)
    content = {
        "texture/SKILL.md": b"---\nname: texture\ndescription: Fixture texture skill\n---\n",
        ".dependency-material/REFERENCE.md": b"---\nname: material\n---\n",
        PUBLIC_HELPER: HELPER,
        SHARED_HELPER: HELPER,
    }
    for relative, raw in content.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(raw)

    sources = {
        "texture/SKILL.md": "skills/texture/SKILL.md",
        ".dependency-material/REFERENCE.md": "tools/blender-tools/REFERENCE.md",
        PUBLIC_HELPER: HELPER_SOURCE,
        SHARED_HELPER: HELPER_SOURCE,
    }
    bundle = root / ".workflow-bundle.json"
    write_json(
        bundle,
        {
            "schema": 1,
            "profile": "sparc3d",
            "entries": ["texture"],
            "files": [[target, sources[target], digest(raw)] for target, raw in content.items()],
        },
    )
    content[bundle.name] = bundle.read_bytes()
    entries = [
        {"name": "texture", "source": "skills/texture"},
        {"name": ".dependency-material", "source": "tools/blender-tools"},
    ]
    write_json(
        root / "prebuilt.json",
        {
            "version": 1,
            "entries": entries,
            "files": [{"path": target, "sha256": digest(raw)} for target, raw in content.items()],
        },
    )
    write_json(
        resources / "runtime" / "manifest.json",
        {
            "runtimeVersion": "1.2.11",
            "platform": "win32",
            "arch": "x64",
            "prebuiltSkills": {"entries": len(entries), "files": len(content)},
        },
    )
    (resources / "runtime" / "support").mkdir()
    (resources / "runtime" / "support" / "fixture.py").write_bytes(b"# Independent runtime script\n")
    (resources / "runtime" / "dist").mkdir()
    (resources / "runtime" / "dist" / "runtime.mjs").write_bytes(b"// Synthetic runtime\n")
    (resources / "notification-icon.png").write_bytes(b"resource fixture\n")
    cache = root / "texture" / "scripts" / "__pycache__"
    cache.mkdir()
    (cache / "material_nodes.pyc").write_bytes(b"locally generated bytecode\n")
    write_archive(resources / "app.asar")


class InventoryTests(unittest.TestCase):
    def setUp(self):
        temporary = TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.resources = self.root / "resources"
        self.output = self.root / "lock"
        fixture(self.resources)

    def run_inventory(
        self, *, resources: Path | None = None, output: Path | None = None, success: bool = True
    ) -> subprocess.CompletedProcess[str]:
        """通过正式 CLI 运行盘点并校验进程结果。

        :param resources: 可选输入目录，默认使用本用例生成的安装包夹具。
        :param output: 可选输出目录，默认使用本用例的锁定目录。
        :param success: 是否预期命令成功。
        :return: 可用于断言错误诊断的进程结果。
        """
        result = subprocess.run(
            [
                sys.executable,
                "-B",
                str(CLI),
                "--resources-root",
                str(resources or self.resources),
                "--output-dir",
                str(output or self.output),
            ],
            cwd=REPO,
            capture_output=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
        message = result.stdout + result.stderr
        if success:
            self.assertEqual(result.returncode, 0, message)
        else:
            self.assertNotEqual(result.returncode, 0, message)
        return result

    def resource_contents(self):
        return {
            path.relative_to(self.resources).as_posix(): path.read_bytes()
            for path in self.resources.rglob("*")
            if path.is_file()
        }

    def test_inventory_hashes_and_paths(self):
        original = self.resource_contents()
        self.run_inventory()
        lines = (self.output / INVENTORY).read_bytes()
        records = [json.loads(line) for line in lines.splitlines()]
        by_path = {entry["path"]: entry for entry in records}
        self.assertEqual(len(by_path), len(records))
        for relative, content in {
            "app.asar/package.json": APP_MEMBER,
            "runtime/support/fixture.py": b"# Independent runtime script\n",
            "notification-icon.png": b"resource fixture\n",
            SKILLS + PUBLIC_HELPER: HELPER,
            SKILLS + SHARED_HELPER: HELPER,
            SKILLS + "prebuilt.json": original[SKILLS + "prebuilt.json"],
        }.items():
            with self.subTest(relative=relative):
                self.assertEqual(by_path[relative]["size"], len(content))
                self.assertEqual(by_path[relative]["sha256"], digest(content))
        for relative in (PUBLIC_HELPER, SHARED_HELPER):
            with self.subTest(relative=relative):
                self.assertEqual(by_path[SKILLS + relative]["source_path"], HELPER_SOURCE)
        self.assertTrue(by_path["app.asar/package.json"]["integrity_verified"])
        self.assertTrue(all("__pycache__" not in relative for relative in by_path))
        self.assertEqual(
            json.loads((self.output / LOCK).read_bytes())["inventory_sha256"], digest(lines)
        )
        self.assertEqual(self.resource_contents(), original)

    def test_rerun_and_relocation_are_byte_identical(self):
        self.run_inventory()
        first = {name: (self.output / name).read_bytes() for name in (INVENTORY, LOCK)}
        first_mtimes = {
            name: (self.output / name).stat().st_mtime_ns for name in (INVENTORY, LOCK)
        }
        self.run_inventory()
        after_mtimes = {
            name: (self.output / name).stat().st_mtime_ns for name in (INVENTORY, LOCK)
        }
        self.assertEqual(after_mtimes, first_mtimes)
        other_resources = self.root / "other" / "resources"
        other_output = self.root / "independent-output"
        fixture(other_resources)
        self.run_inventory(resources=other_resources, output=other_output)
        for name, raw in first.items():
            with self.subTest(name=name):
                self.assertEqual((self.output / name).read_bytes(), raw)
                self.assertEqual((other_output / name).read_bytes(), raw)

    def test_rejects_modified_deployment_file(self):
        (self.resources / SKILLS / PUBLIC_HELPER).write_bytes(b"modified\n")
        self.run_inventory(success=False)
        self.assertFalse((self.output / LOCK).exists())

    def test_rejects_missing_runtime_anchor(self) -> None:
        """校验 Runtime 主程序缺失时拒绝发布盘点和锁定结果。

        :return: 无返回值。
        """
        (self.resources / "runtime" / "dist" / "runtime.mjs").unlink()
        result = self.run_inventory(success=False)
        self.assertIn("runtime/dist/runtime.mjs", result.stderr.replace("\\", "/"))
        self.assertFalse((self.output / INVENTORY).exists())
        self.assertFalse((self.output / LOCK).exists())

    def test_local_cache_changes_leave_release_lock_unchanged(self) -> None:
        """验证本地缓存的增减不会改变同一发行包的盘点和锁定字节。

        :return: 无返回值。
        """
        self.run_inventory()
        original = {name: (self.output / name).read_bytes() for name in (INVENTORY, LOCK)}

        cache = self.resources / SKILLS / "texture" / "scripts" / "__pycache__"
        (cache / "material_nodes.pyc").unlink()
        self.run_inventory()
        for name, content in original.items():
            self.assertEqual((self.output / name).read_bytes(), content)

        (cache / "material_nodes.pyc").write_bytes(b"locally regenerated bytecode\n")
        (self.resources / "runtime" / "support" / "fixture.pyc").write_bytes(b"another cache\n")
        self.run_inventory()
        for name, content in original.items():
            self.assertEqual((self.output / name).read_bytes(), content)

    def test_rejects_inconsistent_source_mapping(self):
        root = self.resources / SKILLS
        bundle = root / ".workflow-bundle.json"
        mappings = json.loads(bundle.read_bytes())
        mappings["files"][0][2] = digest(b"wrong source map digest")
        write_json(bundle, mappings)
        prebuilt = root / "prebuilt.json"
        deploy = json.loads(prebuilt.read_bytes())
        for item in deploy["files"]:
            if item["path"] == bundle.name:
                item["sha256"] = digest(bundle.read_bytes())
        write_json(prebuilt, deploy)
        self.run_inventory(success=False)
        self.assertFalse((self.output / LOCK).exists())

    def test_rejects_output_inside_resources(self):
        output = self.resources / "not-allowed"
        self.run_inventory(output=output, success=False)
        self.assertFalse(output.exists())

    def test_rejects_deployment_manifest_traversal(self):
        outside = self.resources / "runtime" / "outside.txt"
        outside.write_bytes(b"synthetic out-of-scope file\n")
        prebuilt = self.resources / SKILLS / "prebuilt.json"
        deploy = json.loads(prebuilt.read_bytes())
        deploy["files"].append({"path": "../outside.txt", "sha256": digest(outside.read_bytes())})
        write_json(prebuilt, deploy)
        runtime_manifest = self.resources / "runtime" / "manifest.json"
        runtime = json.loads(runtime_manifest.read_bytes())
        runtime["prebuiltSkills"]["files"] = len(deploy["files"])
        write_json(runtime_manifest, runtime)
        self.run_inventory(success=False)
        self.assertFalse((self.output / LOCK).exists())

    def test_rejects_archive_traversal(self):
        write_archive(self.resources / "app.asar", unsafe_name=True)
        self.run_inventory(success=False)
        self.assertFalse((self.output / LOCK).exists())

    def test_rejects_corrupted_archive_member(self):
        write_archive(self.resources / "app.asar", bad_digest=True)
        self.run_inventory(success=False)
        self.assertFalse((self.output / LOCK).exists())

    def test_rejects_bad_asar_block_with_valid_member_digest(self) -> None:
        """验证成员总摘要一致时仍拒绝错误的分块声明。"""
        write_archive(self.resources / "app.asar", bad_block=True)
        result = self.run_inventory(success=False)
        self.assertIn("block", result.stderr.lower())
        self.assertFalse(self.output.exists())

    def test_rejects_linked_archive_before_parsing_target(self) -> None:
        """验证 ASAR 的符号链接检查先于归档解析和锁定输出。

        :return: 无返回值。
        """
        archive = self.resources / "app.asar"
        external = self.root / "external.asar"
        external.write_bytes(b"not an ASAR archive")
        archive.unlink()
        try:
            archive.symlink_to(external)
        except OSError as error:
            self.skipTest(f"当前环境无法创建测试用符号链接：{error}")

        result = self.run_inventory(success=False)
        self.assertRegex(result.stderr, r"(?i)symlink|symbolic link|reparse|符号链接|重解析")
        self.assertFalse((self.output / INVENTORY).exists())
        self.assertFalse((self.output / LOCK).exists())

    def test_does_not_replace_conflicting_inventory(self):
        self.output.mkdir()
        existing = {
            INVENTORY: b'{"fixture":"previous inventory"}\n',
            LOCK: b'{"fixture":"previous lock"}\n',
        }
        for name, content in existing.items():
            (self.output / name).write_bytes(content)
        self.run_inventory(success=False)
        for name, content in existing.items():
            with self.subTest(name=name):
                self.assertEqual((self.output / name).read_bytes(), content)


if __name__ == "__main__":
    unittest.main()
