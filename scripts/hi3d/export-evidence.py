"""Archive allowlisted portable evidence without reading user sessions or credentials.

The reference exporter owns reference.lock.json. This command adds an independent
evidence map, a cache comparison receipt, and explicitly labelled probe fixtures.
It never imports or executes the archived code.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import sys
from collections import Counter
from pathlib import Path, PurePosixPath


LINK = re.compile(r"\]\((<[^>\n]+>|(?:[^()\s]|\([^()]*\))+)\)")
WINDOWS = re.compile(r"^/?[A-Za-z]:[/\\]")
SOURCE_LINE = re.compile(r":(\d+(?:-\d+)?)$")
SAFE_PROBE_GROUPS = (
    "hi3d-retarget-audit-", "hi3d-delivery-export-", "hi3d-source-cache-",
    "hi3d-repair-audit-", "hi3d-reopen-retarget-", "hi3d-reopen-service-",
    "hi3d-retarget-adapter-", "hi3d-axis-tool-probe-",
)
PROBE_SUFFIXES = {".py", ".json", ".blend", ".npz", ".glb"}
SECRET_KEYS = re.compile(
    r"(?i)^(?:api[_-]?key|access[_-]?token|refresh[_-]?token|"
    r"authorization|password|cookie|client[_-]?secret)$"
)
MAX_PROBE_BYTES = 8 * 1024 * 1024
FIXTURE_GUIDE = """# Portable evidence fixtures

These are historical local synthetic probes and three external Blender source
files. They are implementation evidence, not a new test run, a complete Blender
installation, production cloud output or real-animal quality certification.

See [the evidence map](../evidence-map.json) for every original source location,
source SHA-256, archived target, derived SHA-256 and deliberately unarchived gap.
See [the cache receipt](../cache-audit.json) for the exact audited cache scope.

## Provenance

- Original synthetic GLB/BLEND/NPZ and unchanged reports preserve their bytes.
- Sanitized JSON replaces workstation-specific filesystem prefixes.
- Portable Python derivatives are generated by an AST rewrite of known absolute
  path literals. They read HI3D_RESOURCES_ROOT and locate sibling fixture groups
  relative to the copied probe tree. Their hashes differ from the original scripts.
- External Blender source files are byte-preserved excerpts from the recorded
  Windows Blender installation. Retained licence headers apply; these files do not
  form a complete importer/exporter installation.
- The partial REA report and raw production-asset replay log are deliberately not
  copied. Their map entries retain the gap and do not invent substitute results.

## Replaying safely

Do not execute probes in this archived tree: many write reports or candidates
beside the script. Copy the required probe tree to a fresh scratch location, set
HI3D_RESOURCES_ROOT to a verified materialized resources directory, and use a
separately installed compatible Blender with --disable-autoexec and
--python-exit-code 1. No upstream source is executed by the export/verify tools.

Existing reports/candidates are historical results. Some scripts require new
paths and will refuse an existing output. Prepare a fresh run's inputs and output
paths in scratch rather than treating the historical tree as a clean run directory.
This archive does not automatically delete historical reports or regenerate them.

The delivery-export probe uses the sibling reopen-retarget result.blend as a
synthetic input; the axis probe uses the sibling retarget-audit source/cache/config.
The files are provided so these relations can be inspected. Linux Blender replay,
different exporter versions, real quadruped deformation, complete clip/material
coverage and VMware integration remain separate validation work.
"""


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf8")


def relative_path(value: str) -> PurePosixPath:
    path = PurePosixPath(value)
    if not value or "\\" in value or ":" in value or path.is_absolute():
        raise ValueError(f"unsafe relative path: {value}")
    if any(part in ("", ".", "..") for part in value.split("/")):
        raise ValueError(f"unsafe relative path: {value}")
    return path


def within(root: Path, value: str) -> Path:
    relative = relative_path(value)
    result = root.joinpath(*relative.parts)
    if not result.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"path outside root: {value}")
    return result


def collect_links(repo: Path) -> dict[str, list[dict]]:
    """Collect unique filesystem sources; preserve source line and fragment separately."""
    result: dict[str, list[dict]] = {}
    for document in sorted((repo / "docs/hi3d").rglob("*.md")):
        for line_no, line in enumerate(document.read_text(encoding="utf-8-sig").splitlines(), 1):
            for match in LINK.finditer(line):
                link = match.group(1).strip("<>")
                if not WINDOWS.match(link):
                    continue
                source, _, fragment = link.lstrip("/").partition("#")
                source_line = SOURCE_LINE.search(source)
                location = source_line[1] if source_line else None
                if source_line:
                    source = source[:source_line.start()]
                source = source.replace("\\", "/")
                result.setdefault(source, []).append({
                    "document": document.relative_to(repo).as_posix(),
                    "document_line": line_no, "source_line": location,
                    "fragment": fragment or None,
                })
    return result


def sanitize_string(value: str) -> str:
    value = value.replace("\\", "/")
    value = re.sub(
        r"(?i)C:/Users/[^/]+/AppData/Local/Temp",
        "{PROBE_ROOT}", value,
    )
    value = value.replace(
        "D:/install/Hi3DAgent.__hi3d-transaction/resources", "{HI3D_RESOURCES}"
    )
    value = value.replace(
        "D:/download/.sparc3d-runtime/environments/prod", "{RUNTIME_ROOT}"
    )
    value = value.replace("D:/install/blender", "{BLENDER_INSTALL}")
    value = value.replace("D:/Vet3D", "{PROJECT_ROOT}")
    return re.sub(r"(?i)C:/Users/[^/]+", "{USER_HOME}", value)


def clean_json(value: object) -> object:
    if isinstance(value, dict):
        for key in value:
            if SECRET_KEYS.fullmatch(str(key)):
                raise ValueError("credential-shaped field in probe; manual review required")
        return {sanitize_string(str(k)): clean_json(v) for k, v in value.items()}
    if isinstance(value, list):
        return [clean_json(item) for item in value]
    if isinstance(value, str):
        if re.search(r"(?i)\bBearer\s+\S+|[?&](?:token|signature|sig|key)=", value):
            raise ValueError("credential-shaped string in probe; manual review required")
        return sanitize_string(value)
    return value


class PortablePaths(ast.NodeTransformer):
    """Rewrite only known filesystem constants; no code is evaluated."""

    changed = False

    def visit_Constant(self, node: ast.Constant) -> ast.AST:
        if not isinstance(node.value, str):
            return node
        value = node.value.replace("\\", "/")
        installation = "D:/install/Hi3DAgent.__hi3d-transaction/resources"
        marker = "/AppData/Local/Temp/"
        if value == installation or value.startswith(installation + "/"):
            tail = value[len(installation):].lstrip("/")
            expression = "Path(os.environ['HI3D_RESOURCES_ROOT'])"
        elif marker in value and WINDOWS.match(value):
            tail = value.split(marker, 1)[1]
            expression = "Path(__file__).resolve().parents[1]"
        else:
            return node
        if tail:
            expression += " / " + repr(tail)
        self.changed = True
        return ast.copy_location(ast.parse("str(" + expression + ")", mode="eval").body, node)


def portable_probe(path: Path, raw: bytes) -> tuple[bytes, str, str | None]:
    if path.suffix == ".json":
        original = json.loads(raw.decode("utf8"))
        converted = clean_json(original)
        if converted != original:
            return json_bytes(converted), "sanitized", "known filesystem prefixes replaced; UTF-8/LF JSON"
        return raw, "original", None
    if path.suffix == ".py":
        tree = ast.parse(raw.decode("utf8"))
        transformer = PortablePaths()
        tree = transformer.visit(tree)
        if transformer.changed:
            insertion = 0
            if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(tree.body[0].value, ast.Constant) and isinstance(tree.body[0].value.value, str):
                insertion = 1
            while insertion < len(tree.body) and isinstance(tree.body[insertion], ast.ImportFrom) and tree.body[insertion].module == "__future__":
                insertion += 1
            tree.body[insertion:insertion] = [
                ast.Import(names=[ast.alias(name="os")]),
                ast.ImportFrom(module="pathlib", names=[ast.alias(name="Path")], level=0),
            ]
            ast.fix_missing_locations(tree)
            text = "# Portable derivative; original SHA-256 is recorded in evidence-map.json.\n"
            text += ast.unparse(tree) + "\n"
            ast.parse(text)
            return text.encode("utf8"), "sanitized", (
                "AST rewrite of known path literals to HI3D_RESOURCES_ROOT and sibling probe paths"
            )
    return raw, "original", None


def artifact_record(path: str, raw: bytes, original: bytes, mode: str,
                    transformation: str | None, role: str) -> dict:
    return {
        "path": path, "size": len(raw), "sha256": digest(raw),
        "source_sha256": digest(original), "evidence_mode": mode,
        "transformation": transformation, "role": role,
    }


def cache_audit(runtime: Path, resources: dict[str, dict]) -> dict:
    roots = (
        ("deployed_builtin", runtime / "codex-home/skills/buildin"),
        ("user_skills", runtime / "codex-home/skills/user"),
        ("library_revisions", runtime / "skill-library/revisions"),
        ("deployed_tools", runtime / "tools"),
    )
    audits = []
    for role, root in roots:
        counts: Counter = Counter()
        unknown = []
        matched = []
        if root.is_dir():
            for file in sorted(root.rglob("*")):
                if file.is_symlink():
                    counts["symlinks_not_followed"] += 1
                    continue
                if not file.is_file():
                    continue
                relative = file.relative_to(root).as_posix()
                if file.name == ".sparc3d-managed" or file.name == ".sparc3d-skills.json":
                    counts["deployment_metadata_excluded_without_reading"] += 1
                    continue
                if "__pycache__" in file.parts or file.suffix == ".pyc":
                    counts["generated_bytecode_excluded"] += 1
                    continue
                expected = resources.get("runtime/prebuilt-skills/" + relative) if role == "deployed_builtin" else None
                if expected:
                    if file.stat().st_size == expected["size"] and file_digest(file) == expected["sha256"]:
                        counts["identical_to_release"] += 1
                        matched.append((relative, expected["sha256"]))
                        continue
                    counts["different_requires_review"] += 1
                else:
                    counts["unreviewed_not_read_or_archived"] += 1
                unknown.append({"path": relative, "size": file.stat().st_size, "status": "requires_review"})
        audits.append({
            "role": role, "source_root": root.as_posix(), "exists": root.is_dir(),
            "counts": dict(sorted(counts.items())), "unreviewed": unknown,
            "matched_path_hash_list_sha256": digest(json_bytes(matched)),
        })
    return {
        "schema_version": 1, "audit_kind": "allowlisted_implementation_comparison",
        "roots": audits, "exported_cache_implementation_files": [],
        "not_read_or_exported": [
            "auth/cookies/tokens", "sessions/archived_sessions", "raw logs",
            "SQLite/WAL/SHM and runtime configuration", "workspace assets and generated scripts",
            "capture/drafts/operations/workflow graph state", "installation and managed markers",
        ],
        "limits": [
            "Only named implementation roots were enumerated.",
            "Unknown files are listed by relative metadata and require review; not automatically exported.",
            "Empty audited implementation roots do not prove every other runtime directory has no implementation.",
            "Release-identical files are referenced through the fixed archive instead of duplicated.",
        ],
    }


def build_evidence(repo: Path, reference: Path, runtime: Path) -> tuple[dict, dict, dict[str, bytes]]:
    lock = json.loads((reference / "reference.lock.json").read_text(encoding="utf8"))
    resources = {row["path"]: row for row in lock["resources"]}
    artifact_index = {row["path"]: row for row in lock["artifacts"]}
    links = collect_links(repo)
    payloads: dict[str, bytes] = {}
    fixtures: dict[str, dict] = {}

    # Only small synthetic probe groups documented by the earlier analysis are read.
    probe_directories = {
        Path(source).parent for source in links
        if "/AppData/Local/Temp/" in source
        and Path(source).parent.name.startswith(SAFE_PROBE_GROUPS)
    }
    for directory in sorted(probe_directories):
        if not directory.is_dir():
            continue
        for file in sorted(directory.iterdir()):
            if file.is_symlink() or not file.is_file() or file.suffix not in PROBE_SUFFIXES:
                continue
            if file.stat().st_size > MAX_PROBE_BYTES:
                continue
            raw = file.read_bytes()
            converted, mode, transformation = portable_probe(file, raw)
            target = "fixtures/probes/" + directory.name + "/" + file.name
            payloads[target] = converted
            fixtures[file.as_posix()] = artifact_record(
                target, converted, raw, mode, transformation, "documented_synthetic_probe"
            )

    # External Blender code is evidence, not a complete install or a replacement runtime.
    for source in links:
        if source.startswith("D:/install/blender/") and source.endswith(".py"):
            file = Path(source)
            if file.is_file() and not file.is_symlink() and file.stat().st_size <= MAX_PROBE_BYTES:
                raw = file.read_bytes()
                target = "fixtures/external-blender/" + source[len("D:/install/blender/"):]
                payloads[target] = raw
                fixtures[source] = artifact_record(target, raw, raw, "original", None, "external_dependency_source")

    entries = []
    for source, occurrences in sorted(links.items()):
        entry = {
            "source_path": source, "occurrences": occurrences,
            "evidence_mode": "not_archived", "status": "requires_original_environment",
            "target": None, "source_sha256": None, "reason": None,
        }
        marker = "Hi3DAgent.__hi3d-transaction/resources/"
        builtin = "/codex-home/skills/buildin/"
        if marker in source or builtin in source:
            relative = source.split(marker, 1)[1] if marker in source else (
                "runtime/prebuilt-skills/" + source.split(builtin, 1)[1]
            )
            expected = resources.get(relative)
            if expected:
                raw_path = "raw/resources/" + relative
                if raw_path in artifact_index:
                    entry["target"] = {"kind": "repository_file", "path": raw_path, **expected}
                    entry["target"]["path"] = raw_path
                else:
                    entry["target"] = {
                        "kind": "archive_member", "archive": "packages/resources-win-x64.zip",
                        "member": "resources/" + relative, **expected,
                    }
                entry.update(
                    evidence_mode="original", status="archived",
                    source_sha256=expected["sha256"],
                    runtime_requirement="Windows binaries are evidence; script runtime compatibility is separately verified",
                )
            else:
                entry["reason"] = "Not a file in the fixed resource allowlist; deployment metadata is excluded."
        elif source in fixtures:
            artifact = fixtures[source]
            entry.update(
                evidence_mode=artifact["evidence_mode"], status="archived",
                source_sha256=artifact["source_sha256"],
                target={"kind": "repository_file", "path": artifact["path"],
                        "size": artifact["size"], "sha256": artifact["sha256"]},
                transformation=artifact["transformation"],
                runtime_requirement="Reading is portable; Blender replay and animal quality are not asserted.",
            )
        elif source.endswith("/hi3d-studio-export-0yi501pk/index-CDPCug_K.js"):
            target = "raw/app-members/out/renderer/assets/index-CDPCug_K.js"
            if target in artifact_index and Path(source).is_file():
                expected = artifact_index[target]
                if file_digest(Path(source)) != expected["sha256"]:
                    raise ValueError("Temporary renderer differs from fixed ASAR member")
                entry.update(
                    evidence_mode="original", status="archived",
                    source_sha256=expected["sha256"],
                    target={"kind": "repository_file", "path": target,
                            "size": expected["size"], "sha256": expected["sha256"]},
                    reason="Duplicate temporary extraction mapped to the fixed ASAR member.",
                )
        elif "/AppData/Local/Temp/" in source:
            entry["status"] = "not_archived" if Path(source).exists() else "missing"
            entry["reason"] = (
                "Raw replay log or partial REA report not copied; fixed source and safe probes are archived."
                if Path(source).exists() else "Temporary evidence is missing; no replacement result fabricated."
            )
        elif source.startswith("D:/install/blender/"):
            entry["reason"] = "External Windows runtime is not archived or executable on Debian."
        else:
            entry["reason"] = "Personal configuration, user workspace, raw session, graph or log excluded; contents not read."
        entries.append(entry)

    guide = FIXTURE_GUIDE.encode("utf8")
    payloads["fixtures/README.md"] = guide
    audit = cache_audit(runtime, resources)
    audit_bytes = json_bytes(audit)
    manifest = {
        "schema_version": 1, "release": "Hi3D Agent 1.2.11 win32-x64",
        "path_base": "reference directory containing this file",
        "unique_sources": len(entries), "entries": entries,
        "fixtures": sorted(fixtures.values(), key=lambda row: row["path"]),
        "guides": [{"path": "fixtures/README.md", "size": len(guide), "sha256": digest(guide)}],
        "cache_audit": {"path": "cache-audit.json", "size": len(audit_bytes), "sha256": digest(audit_bytes)},
        "limits": [
            "Original workstation paths are provenance metadata, not portable lookup roots.",
            "Sanitized derivatives have separate source and derived hashes; they are not original byte evidence.",
            "Raw sessions, private workspace content and logs are deliberately not read or archived.",
            "Probe binaries are documented synthetic fixtures, not real animal validation or branch coverage.",
            "Portable probe scripts require HI3D_RESOURCES_ROOT and a separate scratch copy of the probe tree.",
            "Blender execution, cloud models and VMware integration require their own validation.",
        ],
    }
    return manifest, audit, payloads


def verify_evidence(repo: Path, reference: Path) -> dict:
    manifest = json.loads((reference / "evidence-map.json").read_text(encoding="utf8"))
    if manifest.get("schema_version") != 1:
        raise ValueError("unsupported evidence schema")
    for row in manifest.get("guides", []):
        path = within(reference, row["path"])
        if not path.is_file() or path.is_symlink() or path.stat().st_size != row["size"] or file_digest(path) != row["sha256"]:
            raise ValueError("evidence guide bytes differ")
    fixtures = {}
    for row in manifest["fixtures"]:
        if row["path"] in fixtures:
            raise ValueError("duplicate fixture path")
        fixtures[row["path"]] = row
        path = within(reference, row["path"])
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"missing or linked fixture: {row['path']}")
        if path.stat().st_size != row["size"] or file_digest(path) != row["sha256"]:
            raise ValueError(f"fixture bytes differ: {row['path']}")
        if row["evidence_mode"] == "original":
            if row["source_sha256"] != row["sha256"]:
                raise ValueError("original fixture has changed bytes")
        elif row["evidence_mode"] != "sanitized" or not row["transformation"]:
            raise ValueError("unlabelled fixture transformation")
    actual_sources = set(collect_links(repo))
    mapped_sources = set()
    lock = json.loads((reference / "reference.lock.json").read_text(encoding="utf8"))
    resource_rows = {row["path"]: row for row in lock["resources"]}
    artifact_rows = {row["path"]: row for row in lock["artifacts"]}
    verified_archives = set()
    for entry in manifest["entries"]:
        source = entry["source_path"]
        if source in mapped_sources:
            raise ValueError("duplicate evidence source")
        mapped_sources.add(source)
        for occurrence in entry["occurrences"]:
            if not within(repo, occurrence["document"]).is_file():
                raise ValueError("missing evidence document")
        target = entry.get("target")
        mode = entry["evidence_mode"]
        status = entry["status"]
        if mode not in {"original", "sanitized", "not_archived"}:
            raise ValueError("unknown evidence mode")
        if target is None:
            if (mode != "not_archived" or not entry["reason"]
                    or status not in {"requires_original_environment", "not_archived", "missing"}):
                raise ValueError("unlabelled evidence gap")
            continue
        if status != "archived" or mode == "not_archived":
            raise ValueError("evidence mode/status/target conflict")
        if target["kind"] == "repository_file":
            row = fixtures.get(target["path"]) or artifact_rows.get(target["path"])
            if row is None:
                raise ValueError("unregistered evidence target")
            expected_mode = row.get("evidence_mode", "original")
            if mode != expected_mode or entry["source_sha256"] != row.get("source_sha256", row["sha256"]):
                raise ValueError("evidence label differs from target provenance")
            if mode == "sanitized" and not entry.get("transformation"):
                raise ValueError("unlabelled evidence conversion")
            path = within(reference, target["path"])
            if (not path.is_file() or path.is_symlink() or path.stat().st_size != target["size"]
                    or file_digest(path) != target["sha256"]):
                raise ValueError("evidence file bytes differ")
        elif target["kind"] == "archive_member":
            archive = lock.get("archive")
            if archive is None or target["archive"] != archive["path"]:
                raise ValueError("evidence archive differs from release archive")
            if mode != "original":
                raise ValueError("archive member must preserve original evidence")
            member = str(relative_path(target["member"]))
            if not member.startswith("resources/"):
                raise ValueError("invalid resource member")
            row = resource_rows.get(member[len("resources/"):])
            if row is None:
                raise ValueError("archive source not in fixed release")
            archive_path = within(reference, target["archive"])
            expected_archive = artifact_rows.get(target["archive"])
            if expected_archive is None or any(expected_archive[key] != archive[key] for key in ("size", "sha256")):
                raise ValueError("archive metadata differs from artifact manifest")
            if target["archive"] not in verified_archives:
                if (not archive_path.is_file() or archive_path.is_symlink()
                        or archive_path.stat().st_size != archive["size"]
                        or file_digest(archive_path) != archive["sha256"]):
                    raise ValueError("evidence archive bytes differ")
                verified_archives.add(target["archive"])
        else:
            raise ValueError("unknown evidence target kind")
        if row["sha256"] != target["sha256"] or row["size"] != target["size"]:
            raise ValueError("target differs from corresponding manifest")
        if entry["evidence_mode"] == "original" and entry["source_sha256"] != target["sha256"]:
            raise ValueError("original evidence source hash differs")
    if actual_sources != mapped_sources or len(mapped_sources) != manifest["unique_sources"]:
        raise ValueError("document evidence coverage changed")
    audit = json.loads((reference / "cache-audit.json").read_text(encoding="utf8"))
    if "cache_audit" in manifest:
        row = manifest["cache_audit"]
        if row["path"] != "cache-audit.json":
            raise ValueError("unexpected cache audit path")
        path = within(reference, row["path"])
        if path.stat().st_size != row["size"] or file_digest(path) != row["sha256"]:
            raise ValueError("cache audit bytes differ")
    if audit.get("schema_version") != 1:
        raise ValueError("unsupported cache audit schema")
    if audit["exported_cache_implementation_files"]:
        raise ValueError("cache delta needs an explicit reviewed artifact manifest")
    return {"sources": len(mapped_sources), "fixtures": len(fixtures), "cache_roots": len(audit["roots"])}


def export_evidence(repo: Path, reference: Path, runtime: Path) -> dict:
    manifest, audit, payloads = build_evidence(repo, reference, runtime)
    payloads["cache-audit.json"] = json_bytes(audit)
    payloads["evidence-map.json"] = json_bytes(manifest)
    # Validate collisions before mutation; existing equal content is a verified reuse.
    for name, data in payloads.items():
        path = within(reference, name)
        if path.is_symlink() or (path.exists() and (not path.is_file() or path.read_bytes() != data)):
            raise ValueError(f"existing evidence differs: {name}")
    for name, data in payloads.items():
        path = within(reference, name)
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("xb") as stream:
                stream.write(data)
    return verify_evidence(repo, reference)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--reference-dir", type=Path, required=True)
    parser.add_argument("--runtime-root", type=Path)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.verify:
            result = verify_evidence(args.repo_root.resolve(), args.reference_dir.resolve())
        else:
            if args.runtime_root is None:
                parser.error("--runtime-root is required when exporting")
            result = export_evidence(
                args.repo_root.resolve(), args.reference_dir.resolve(), args.runtime_root.resolve()
            )
        print(json.dumps(result, ensure_ascii=False, sort_keys=True))
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"evidence error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
