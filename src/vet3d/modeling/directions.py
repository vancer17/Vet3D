# 文件信息：L0-03 的唯一五向业务语义。
# 作用：用动物自身侧别描述观察方向，供选图、取证和后续适配器共同消费。
# 边界：不是供应商槽位、画面鼻尖方向或图片方向识别结果。
"""定义前、后、左、右、顶五个业务方向。"""

from enum import StrEnum


class ViewDirection(StrEnum):
    """表示观察者相对于动物主体的位置，不使用供应商方向名称定义侧别。"""

    # 前视：观察者位于动物头端，面向主体。
    FRONT = "front"
    # 后视：观察者位于动物尾端，面向主体。
    BACK = "back"
    # 左视：观察者位于动物自身左侧。
    LEFT = "left"
    # 右视：观察者位于动物自身右侧。
    RIGHT = "right"
    # 顶视：观察者位于动物背侧上方，规范画面中头端朝上。
    TOP = "top"
